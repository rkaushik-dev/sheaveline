-- The weather log: the stations, and every reading they send.

CREATE TABLE weather_stations (
    name VARCHAR(32) NOT NULL,
    elevation INTEGER NOT NULL,
    CONSTRAINT pk_weather_stations PRIMARY KEY (name)
);

CREATE TABLE observations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    station_name VARCHAR(32) NOT NULL,
    taken TIMESTAMP(6) NOT NULL,
    wind_speed INTEGER NOT NULL,
    wind_bearing INTEGER NOT NULL,
    wind_gust INTEGER,
    temperature INTEGER NOT NULL,
    visibility INTEGER NOT NULL,
    precipitation VARCHAR(32) NOT NULL,
    rime BOOLEAN NOT NULL,
    lightning_within INTEGER,
    CONSTRAINT ck_observations_visibility_not_negative CHECK (visibility >= 0),
    CONSTRAINT ck_observations_gust_above_sustained CHECK (wind_gust IS NULL OR wind_gust >= wind_speed),
    CONSTRAINT fk_observations_station_name_weather_stations
        FOREIGN KEY (station_name) REFERENCES weather_stations (name),
    CONSTRAINT pk_observations PRIMARY KEY (id),
    CONSTRAINT one_reading_a_moment UNIQUE (station_name, taken)
);
