    CONSTRAINT ck_meter_readings_cycles_not_negative CHECK (cycles >= 0),
    CONSTRAINT ck_meter_readings_hours_not_negative CHECK (hours >= 0),
    CONSTRAINT fk_meter_readings_lift_code_lifts FOREIGN KEY (lift_code) REFERENCES lifts (code),
    CONSTRAINT pk_meter_readings PRIMARY KEY (id),
    CONSTRAINT one_reading_a_day UNIQUE (lift_code, day)
);

CREATE TABLE stops (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    lift_code VARCHAR(8) NOT NULL,
    kind VARCHAR(32) NOT NULL,
