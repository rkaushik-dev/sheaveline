    CONSTRAINT fk_inspection_records_lift_code_lifts FOREIGN KEY (lift_code) REFERENCES lifts (code),
    CONSTRAINT pk_inspection_records PRIMARY KEY (id),
    CONSTRAINT one_record_a_job_a_day UNIQUE (lift_code, code, done)
);

CREATE TABLE meter_readings (
