-- The baseline: the plant, the rope file, the day on the hill, upkeep, and the board's paperwork.
--
-- Measures are whole numbers in their base unit, identifiers keep their printed form, and
-- enumerations are stored by their constant's name. Every constraint carries the name the naming
-- convention gives it. "ON" and "WHERE" are quoted because they are keywords.

CREATE TABLE certificates (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    person VARCHAR(64) NOT NULL,
    endorsement VARCHAR(32) NOT NULL,
    issued DATE NOT NULL,
    expires DATE NOT NULL,
    issued_by VARCHAR(64) NOT NULL,
    CONSTRAINT ck_certificates_card_runs_forwards CHECK (expires > issued),
    CONSTRAINT pk_certificates PRIMARY KEY (id),
    CONSTRAINT one_card_an_issue UNIQUE (person, endorsement, issued)
);

CREATE TABLE filing_counters (
    state VARCHAR(2) NOT NULL,
    year INTEGER NOT NULL,
    next_sequence INTEGER NOT NULL,
    CONSTRAINT pk_filing_counters PRIMARY KEY (state, year)
);

CREATE TABLE lifts (
    code VARCHAR(8) NOT NULL,
    name VARCHAR(64) NOT NULL,
    lift_class VARCHAR(32) NOT NULL,
    bearing INTEGER NOT NULL,
    design_speed INTEGER NOT NULL,
    commissioned DATE NOT NULL,
    CONSTRAINT ck_lifts_speed_positive CHECK (design_speed > 0),
    CONSTRAINT pk_lifts PRIMARY KEY (code)
);

CREATE TABLE rope_specs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    construction VARCHAR(32) NOT NULL,
    grade VARCHAR(32) NOT NULL,
    lay VARCHAR(32) NOT NULL,
    nominal_diameter INTEGER NOT NULL,
    breaking_strength INTEGER NOT NULL,
    weight INTEGER NOT NULL,
    CONSTRAINT pk_rope_specs PRIMARY KEY (id)
);

CREATE TABLE assignments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    lift_code VARCHAR(8) NOT NULL,
    day DATE NOT NULL,
    person VARCHAR(64) NOT NULL,
    post VARCHAR(32) NOT NULL,
    starts INTEGER NOT NULL,
    ends INTEGER NOT NULL,
    CONSTRAINT ck_assignments_shift_runs_forwards CHECK (ends > starts),
    CONSTRAINT fk_assignments_lift_code_lifts FOREIGN KEY (lift_code) REFERENCES lifts (code),
    CONSTRAINT pk_assignments PRIMARY KEY (id),
    CONSTRAINT one_shift_a_start UNIQUE (lift_code, day, person, starts)
);

CREATE TABLE carriers (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    lift_code VARCHAR(8) NOT NULL,
    number INTEGER NOT NULL,
    kind VARCHAR(32) NOT NULL,
    tare INTEGER NOT NULL,
    hanger INTEGER NOT NULL,
    restraining_bar BOOLEAN NOT NULL,
    in_service BOOLEAN NOT NULL,
    grip_kind VARCHAR(32),
    grip_model VARCHAR(32),
    grip_jaws INTEGER,
    grip_spring_pack VARCHAR(32),
    grip_rated_slip INTEGER,
    grip_installed DATE,
    CONSTRAINT ck_carriers_carriers_from_one CHECK (number >= 1),
    CONSTRAINT fk_carriers_lift_code_lifts FOREIGN KEY (lift_code) REFERENCES lifts (code),
    CONSTRAINT pk_carriers PRIMARY KEY (id),
    CONSTRAINT one_number_a_fleet UNIQUE (lift_code, number)
);

CREATE TABLE certificate_classes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    certificate_id INTEGER NOT NULL,
    lift_class VARCHAR(32) NOT NULL,
    CONSTRAINT fk_certificate_classes_certificate_id_certificates
        FOREIGN KEY (certificate_id) REFERENCES certificates (id),
    CONSTRAINT pk_certificate_classes PRIMARY KEY (id),
    CONSTRAINT one_class_a_card UNIQUE (certificate_id, lift_class)
);

CREATE TABLE day_logs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    lift_code VARCHAR(8) NOT NULL,
    day DATE NOT NULL,
    first_load INTEGER NOT NULL,
    last_load INTEGER NOT NULL,
    sweep_by INTEGER NOT NULL,
    opened INTEGER,
    closed INTEGER,
    mechanic VARCHAR(64),
    operator VARCHAR(64),
    CONSTRAINT ck_day_logs_loads_in_order CHECK (last_load >= first_load),
    CONSTRAINT ck_day_logs_sweep_after_last_load CHECK (sweep_by >= last_load),
    CONSTRAINT fk_day_logs_lift_code_lifts FOREIGN KEY (lift_code) REFERENCES lifts (code),
    CONSTRAINT pk_day_logs PRIMARY KEY (id),
    CONSTRAINT one_log_a_day UNIQUE (lift_code, day)
);

CREATE TABLE drills (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    lift_code VARCHAR(8) NOT NULL,
    "ON" DATE NOT NULL,
    kind VARCHAR(32) NOT NULL,
    carriers_worked INTEGER NOT NULL,
    elapsed_seconds INTEGER NOT NULL,
    observer VARCHAR(64) NOT NULL,
    CONSTRAINT ck_drills_carriers_not_negative CHECK (carriers_worked >= 0),
    CONSTRAINT fk_drills_lift_code_lifts FOREIGN KEY (lift_code) REFERENCES lifts (code),
    CONSTRAINT pk_drills PRIMARY KEY (id),
    CONSTRAINT one_drill_a_day UNIQUE (lift_code, "ON")
);

CREATE TABLE filings (
    number VARCHAR(16) NOT NULL,
    kind VARCHAR(32) NOT NULL,
    lift_code VARCHAR(8) NOT NULL,
    filed TIMESTAMP(6) NOT NULL,
    about VARCHAR(1000) NOT NULL,
    filed_by VARCHAR(64) NOT NULL,
    acknowledged DATE,
    CONSTRAINT fk_filings_lift_code_lifts FOREIGN KEY (lift_code) REFERENCES lifts (code),
    CONSTRAINT pk_filings PRIMARY KEY (number)
);

CREATE TABLE haul_ropes (
    serial VARCHAR(20) NOT NULL,
    spec_id INTEGER NOT NULL,
    lift_code VARCHAR(8),
    installed DATE NOT NULL,
    length INTEGER NOT NULL,
    splices INTEGER NOT NULL,
    CONSTRAINT ck_haul_ropes_splices_not_negative CHECK (splices >= 0),
    CONSTRAINT fk_haul_ropes_lift_code_lifts FOREIGN KEY (lift_code) REFERENCES lifts (code),
    CONSTRAINT fk_haul_ropes_spec_id_rope_specs FOREIGN KEY (spec_id) REFERENCES rope_specs (id),
    CONSTRAINT pk_haul_ropes PRIMARY KEY (serial)
);

CREATE TABLE holds (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    lift_code VARCHAR(8) NOT NULL,
    reason VARCHAR(32) NOT NULL,
    started TIMESTAMP(6) NOT NULL,
    started_by VARCHAR(64) NOT NULL,
    detail VARCHAR(500) NOT NULL,
    ended TIMESTAMP(6),
    ended_by VARCHAR(64),
    CONSTRAINT ck_holds_hold_ends_after_it_starts CHECK (ended IS NULL OR ended >= started),
    CONSTRAINT fk_holds_lift_code_lifts FOREIGN KEY (lift_code) REFERENCES lifts (code),
    CONSTRAINT pk_holds PRIMARY KEY (id)
);

CREATE TABLE inspection_records (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    lift_code VARCHAR(8) NOT NULL,
    code VARCHAR(4) NOT NULL,
    done DATE NOT NULL,
    by VARCHAR(64) NOT NULL,
    hours INTEGER,
