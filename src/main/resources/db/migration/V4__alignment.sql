-- The towers get shot every autumn, and the shots have to live somewhere.

CREATE TABLE alignment_surveys (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    lift_code VARCHAR(8) NOT NULL,
    taken DATE NOT NULL,
    surveyor VARCHAR(64) NOT NULL,
    CONSTRAINT fk_alignment_surveys_lift_code_lifts FOREIGN KEY (lift_code) REFERENCES lifts (code),
    CONSTRAINT pk_alignment_surveys PRIMARY KEY (id),
    CONSTRAINT one_alignment_survey_a_day UNIQUE (lift_code, taken)
);

CREATE INDEX ix_alignment_by_machine ON alignment_surveys (lift_code, taken);

CREATE TABLE tower_shots (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    survey_id INTEGER NOT NULL,
    tower_ref VARCHAR(16) NOT NULL,
    station INTEGER NOT NULL,
    crossarm_elevation INTEGER NOT NULL,
    offset_at_top INTEGER NOT NULL,
    CONSTRAINT ck_tower_shots_shot_station_not_negative CHECK (station >= 0),
    CONSTRAINT fk_tower_shots_survey_id_alignment_surveys FOREIGN KEY (survey_id) REFERENCES alignment_surveys (id),
    CONSTRAINT pk_tower_shots PRIMARY KEY (id),
    CONSTRAINT one_shot_a_tower UNIQUE (survey_id, tower_ref)
);
